#!/usr/bin/env python3
"""Convert the web app's flat emblem SVGs into Android vector drawables.

    python3 tools/emblem_to_vector.py [path/to/north-web-app/static/assets/brand/solar]

Writes core/designsystem/src/main/res/drawable/khepri_emblem_light.xml and
khepri_emblem_dark.xml. They are separate names, not a -night pair, because the
app's Appearance setting can differ from the system's. Handles what the emblem uses: circles,
paths, solid fills and strokes, and one objectBoundingBox radial gradient.
"""

import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_SOURCE = ROOT.parent / "north-web-app/static/assets/brand/solar"
OUT = ROOT / "core/designsystem/src/main/res"
SVG = "{http://www.w3.org/2000/svg}"
CAPS = {"round": "round", "square": "square", "butt": "butt"}


def circle_path(cx: float, cy: float, r: float) -> str:
    return f"M{cx - r:g},{cy}a{r:g},{r:g} 0,1 1,{2 * r:g},0a{r:g},{r:g} 0,1 1,{-2 * r:g},0z"


def gradient_xml(gradient: ET.Element, box: tuple[float, float, float, float], indent: str) -> str:
    x, y, w, h = box
    cx = x + float(gradient.get("cx", "0.5")) * w
    cy = y + float(gradient.get("cy", "0.5")) * h
    r = float(gradient.get("r", "0.5")) * w
    stops = "".join(
        f'\n{indent}        <item android:offset="{s.get("offset")}" android:color="{s.get("stop-color")}" />'
        for s in gradient.iter(f"{SVG}stop")
    )
    return (
        f'\n{indent}<aapt:attr name="android:fillColor">'
        f'\n{indent}    <gradient android:type="radial" android:centerX="{cx:g}" android:centerY="{cy:g}"'
        f' android:gradientRadius="{r:g}">{stops}'
        f"\n{indent}    </gradient>"
        f"\n{indent}</aapt:attr>"
    )


def convert(svg_path: Path) -> str:
    root = ET.parse(svg_path).getroot()
    min_x, min_y, width, height = (float(v) for v in root.get("viewBox").split())
    gradients = {g.get("id"): g for g in root.iter(f"{SVG}radialGradient")}
    paths = []
    indent = "        "
    for element in root:
        tag = element.tag.removeprefix(SVG)
        if tag == "circle":
            cx, cy, r = (float(element.get(k)) for k in ("cx", "cy", "r"))
            data, box = circle_path(cx, cy, r), (cx - r, cy - r, 2 * r, 2 * r)
        elif tag == "path":
            data, box = re.sub(r"\s+", " ", element.get("d")).strip(), None
        else:
            continue
        attrs = [f'android:pathData="{data}"']
        fill = element.get("fill")
        body = ""
        if fill and fill.startswith("url(#"):
            if box is None:
                raise ValueError("gradient fills are supported on circles only")
            body = gradient_xml(gradients[fill[5:-1]], box, indent + "    ")
        elif fill and fill != "none":
            attrs.append(f'android:fillColor="{fill}"')
        if element.get("stroke"):
            attrs.append(f'android:strokeColor="{element.get("stroke")}"')
            attrs.append(f'android:strokeWidth="{element.get("stroke-width", "1")}"')
            if element.get("stroke-linecap") in CAPS:
                attrs.append(f'android:strokeLineCap="{element.get("stroke-linecap")}"')
            if element.get("stroke-linejoin"):
                attrs.append(f'android:strokeLineJoin="{element.get("stroke-linejoin")}"')
        joined = f"\n{indent}    ".join(attrs)
        if body:
            paths.append(f"{indent}<path\n{indent}    {joined}>{body}\n{indent}</path>")
        else:
            paths.append(f"{indent}<path\n{indent}    {joined} />")
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        f"<!-- Generated by tools/emblem_to_vector.py from {svg_path.name}. Do not edit. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    xmlns:aapt="http://schemas.android.com/aapt"\n'
        '    android:width="120dp"\n'
        '    android:height="120dp"\n'
        f'    android:viewportWidth="{width:g}"\n'
        f'    android:viewportHeight="{height:g}">\n'
        f'    <group android:translateX="{-min_x:g}" android:translateY="{-min_y:g}">\n'
        + "\n".join(paths)
        + "\n    </group>\n</vector>\n"
    )


def main() -> int:
    source = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_SOURCE
    for mode in ("light", "dark"):
        name = f"khepri-emblem-{mode}.svg"
        out = OUT / "drawable" / f"khepri_emblem_{mode}.xml"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(convert(source / name), encoding="utf-8")
        print(f"wrote {out.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
